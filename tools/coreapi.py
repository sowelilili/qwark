"""coreapi.py: the seam between qwark's core and its games (SPEC-game-modules.md 4.4).

    python -I tools/coreapi.py              write the four generated files
    python -I tools/coreapi.py --check      fail when any of them is stale
    python -I tools/coreapi.py nmcheck <llvm-nm> <game objects...>
                                            fail when a game object calls the
                                            core other than through core_api

src/games/core_api.txt lists every core function a game may call. From it:

  src/games/core_api.h     struct core_api: one pointer per function, named
                           x_<function> so the renames below never touch it
  src/games/core_import.h  #define <function> qimp_<function>, for a game's
                           sources, which include it before anything else
  src/games/core_import.c  the wrappers: qimp_<function>(...) calls Q->api
  src/core/core_export.c   the core's table of its own functions

A game module has no writable data, so it cannot keep a pointer to the core's
table itself: Q is the core's context (src/games/module.h), r14 on the console
and an ordinary pointer on a PC. The host builds keep the games linked and go
through the same wrappers, which is what nmcheck holds them to.

Stdlib only; safe under python -I.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST = os.path.join(ROOT, "src", "games", "core_api.txt")
OUT_API = os.path.join(ROOT, "src", "games", "core_api.h")
OUT_RENAME = os.path.join(ROOT, "src", "games", "core_import.h")
OUT_IMPORT = os.path.join(ROOT, "src", "games", "core_import.c")
OUT_EXPORT = os.path.join(ROOT, "src", "core", "core_export.c")

BANNER = ("/*\n * Generated by tools/coreapi.py from src/games/core_api.txt: do not edit.\n"
          " * Change the list and run `python -I tools/coreapi.py`.\n */\n")

# What a game object may leave undefined besides the wrappers: the C library
# the compiler itself calls (struct copies and clears), which a game module
# links from src/plat/ps3/libc.c, and the toolchain's own helpers.
LIBC = {"memset", "memcmp", "memcpy", "memmove", "strlen", "__chkstk_ms", "___chkstk_ms",
        "__main", "_fltused"}


def die(msg):
    sys.stderr.write("coreapi.py: %s\n" % msg)
    sys.exit(1)


class Fn(object):
    def __init__(self, cond, ret, name, params, vfn):
        self.cond, self.ret, self.name, self.params, self.vfn = cond, ret, name, params, vfn

    def variadic(self):
        return self.params and self.params[-1] == "..."

    def fixed(self):
        return [p for p in self.params if p != "..."]

    def arg_names(self):
        out = []
        for p in self.fixed():
            m = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*$", p)
            if not m:
                die("no parameter name in %r (%s)" % (p, self.name))
            out.append(m.group(1))
        return out

    def ptype(self):
        ps = self.fixed() + (["va_list ap"] if self.variadic() else [])
        return "%s (*x_%s)(%s)" % (self.ret, self.table_name(), ", ".join(ps) or "void")

    def table_name(self):
        return self.vfn or self.name


def parse():
    includes, fns = [], []
    with open(LIST, "r") as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            if line.startswith("#include"):
                includes.append(line)
                continue
            if line.startswith("#"):
                continue
            m = re.match(r"^(?:\[([A-Z_0-9]+)\]\s*)?(.+?)\(([^()]*)\)\s*(?:->\s*([A-Za-z_0-9]+))?$", line)
            if not m:
                die("line %d: not a prototype: %s" % (n, line))
            cond, head, params, vfn = m.groups()
            hm = re.match(r"^(.*?)([A-Za-z_][A-Za-z0-9_]*)$", head.strip())
            if not hm:
                die("line %d: no function name: %s" % (n, line))
            ret, name = hm.group(1).strip(), hm.group(2)
            ps = [p.strip() for p in params.split(",")] if params.strip() not in ("", "void") else []
            fn = Fn(cond, ret, name, ps, vfn)
            if fn.variadic() and not vfn:
                die("line %d: %s is variadic: name its va_list function after ->" % (n, name))
            fns.append(fn)
    names = [f.name for f in fns]
    if len(set(names)) != len(names):
        die("a function is listed twice")
    return includes, fns


def guarded(fn, text):
    if not fn.cond:
        return text
    return "#ifdef %s\n%s#endif\n" % (fn.cond, text)


def gen(includes, fns):
    api = [BANNER, "#ifndef QWARK_CORE_API_H\n#define QWARK_CORE_API_H\n\n"]
    api += [i + "\n" for i in includes]
    api.append("\n#include <stdarg.h>\n\n")
    api.append("/*\n * The core's functions, in core_api.txt's order. A module refuses a\n"
               " * table of any other size (src/games/module.h, api_size), so a module and\n"
               " * a core from different lists never meet.\n */\n")
    api.append("struct core_api {\n")
    for f in fns:
        api.append(guarded(f, "\t%s;\n" % f.ptype()))
    api.append("};\n\n")
    api.append("/* The core's own table (src/core/core_export.c). */\n")
    api.append("extern const struct core_api core_api_table;\n\n")
    api.append("#endif /* QWARK_CORE_API_H */\n")

    ren = [BANNER, "/*\n * The first include of every game source. Where the games reach the core\n"
                   " * through core_api (QWARK_GAME_IMPORT, src/games/module.h), each core\n"
                   " * function a game names is the wrapper of the same name in\n"
                   " * core_import.c instead; elsewhere (a QWARK_GAME_MODULES 0 module, whose\n"
                   " * games are linked in and call the core directly) this file is empty.\n */\n",
           "#ifndef QWARK_CORE_IMPORT_H\n#define QWARK_CORE_IMPORT_H\n\n",
           "/* Nothing before the renames but the build's modes: no header has declared anything yet. */\n",
           "#include \"../core/buildmodes.h\"\n\n#if QWARK_GAME_IMPORT\n"]
    for f in fns:
        ren.append(guarded(f, "#define %s qimp_%s\n" % (f.name, f.name)))
    ren.append("#endif\n\n#endif /* QWARK_CORE_IMPORT_H */\n")

    imp = [BANNER, "/*\n * The wrappers a game's calls into the core land on, one per function of\n"
                   " * core_api.txt: each passes its arguments on through the core's table,\n"
                   " * which Q holds (src/games/module.h). Linked into every game module, and\n"
                   " * into the host builds, whose games go through them too.\n */\n",
           "#include \"module.h\"   /* first: Q is a register on the console */\n"
           "#include \"core_api.h\"\n\n#if QWARK_GAME_IMPORT\n\n"]
    for f in fns:
        names = f.arg_names()
        proto = "%s qimp_%s(%s)" % (f.ret, f.name, ", ".join(f.params) or "void")
        call = "Q->api->x_%s(%s)" % (f.table_name(), ", ".join(names + (["ap"] if f.variadic() else [])))
        if f.variadic():
            last = names[-1]
            body = ("{\n\tva_list ap;\n\n\tva_start(ap, %s);\n\t%s%s;\n\tva_end(ap);\n}\n"
                    % (last, "" if f.ret == "void" else "(void)", call))
            if f.ret != "void":
                die("%s: a variadic wrapper returns nothing" % f.name)
        elif f.ret == "void":
            body = "{\n\t%s;\n}\n" % call
        else:
            body = "{\n\treturn %s;\n}\n" % call
        imp.append(guarded(f, "%s\n%s" % (proto, body)) + "\n")
    imp.append("#endif /* QWARK_GAME_IMPORT */\n")

    exp = [BANNER, "/*\n * The table the core hands a game module at its start, and the host builds\n"
                   " * their linked games (src/games/module.h). Only where the games go through\n"
                   " * core_api: a QWARK_GAME_MODULES 0 module's games call the core directly.\n */\n",
           "#include \"../games/core_api.h\"\n#include \"../games/module.h\"\n\n#if QWARK_GAME_IMPORT\n\n",
           "const struct core_api core_api_table = {\n"]
    for f in fns:
        exp.append(guarded(f, "\t.x_%s = %s,\n" % (f.table_name(), f.table_name())))
    exp.append("};\n\n#endif /* QWARK_GAME_IMPORT */\n")
    return {OUT_API: "".join(api), OUT_RENAME: "".join(ren), OUT_IMPORT: "".join(imp),
            OUT_EXPORT: "".join(exp)}


def write_or_check(files, check):
    stale = []
    for path, text in sorted(files.items()):
        old = None
        if os.path.exists(path):
            with open(path, "rb") as f:
                old = f.read().decode("utf-8").replace("\r\n", "\n")
        if old == text:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            with open(path, "wb") as f:
                f.write(text.encode("utf-8"))
            print("coreapi.py: wrote %s" % os.path.relpath(path, ROOT))
    if stale:
        die("stale (run python -I tools/coreapi.py): %s" % ", ".join(stale))
    if check:
        print("coreapi.py: the generated files match core_api.txt")


def nm_symbols(nm, obj, flag):
    out = subprocess.run([nm, flag, obj], stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                         timeout=60)
    if out.returncode != 0:
        die("%s %s %s: %s" % (nm, flag, obj, out.stderr.decode("utf-8", "replace")[:400]))
    syms = set()
    for line in out.stdout.decode("utf-8", "replace").splitlines():
        parts = line.split()
        if not parts or line.endswith(":"):
            continue
        syms.add(parts[-1])
    return syms


def nmcheck(nm, objs):
    _inc, fns = parse()
    wrappers = set("qimp_" + f.name for f in fns)
    defined, undefined = set(), {}
    for o in objs:
        defined |= nm_symbols(nm, o, "--defined-only")
        for s in nm_symbols(nm, o, "-u"):
            undefined.setdefault(s, []).append(os.path.basename(o))
    bad = []
    for s, users in sorted(undefined.items()):
        if s in defined or s in wrappers or s in LIBC:
            continue
        if s.startswith("__imp_") or s.startswith(".refptr."):
            continue
        bad.append("%s (%s)" % (s, ", ".join(sorted(set(users)))))
    if bad:
        die("game objects reach the core around core_api: " + "; ".join(bad))
    print("coreapi.py: %d game objects reach the core through core_api alone (%d functions)"
          % (len(objs), len(fns)))


def main(argv):
    if len(argv) >= 3 and argv[1] == "nmcheck":
        nmcheck(argv[2], argv[3:])
        return
    includes, fns = parse()
    write_or_check(gen(includes, fns), len(argv) > 1 and argv[1] == "--check")


if __name__ == "__main__":
    main(sys.argv)
